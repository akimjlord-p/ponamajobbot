class Prompts:
    @staticmethod
    def get_prompt_for_synonym(word: str) -> str:
        return f"""
Тебе дано одно слово: название товара или операции.
Верни только полезные для распознавания варианты написания.

Правила:
- включи русский вариант;
- включи английский вариант, только если он реально используется;
- включи реалистичный транслит, если он помогает распознаванию;
- не добавляй абстрактные близкие по смыслу слова;
- не добавляй редкие или спорные варианты;
- все слова в нижнем регистре;
- только список через запятую без пробелов;
- без пояснений и дублей.

Слово: {word}
""".strip()

    @staticmethod
    def get_report_parsing_prompt(report_text: str, parsing_context: str | None = None) -> str:
        context_block = parsing_context or "Нет дополнительного контекста"

        return f"""
Ты парсер рабочих отчетов сотрудников.

Задача:
1. Определи, можно ли извлечь из отчета выполненные операции.
2. Если можно, верни список операций.
3. Операция:
   - operation_type_name: тип операции, например сборка/покраска/упаковка;
   - product_name: объект операции, например коробка/куртка/кружка;
   - quantity: количество выполненных действий, целое число.
   Пример: "покрасил 5 кружек" -> operation_type_name="покраска", product_name="кружка", quantity=5.
4. Если операций нет, но текст полезен для бизнеса, верни text_only.
5. Если отчет трудно разобрать или есть вопросы, верни no_actionable_data.
6. Если не уверен в операции или товаре, лучше верни no_actionable_data.

Дополнительный контекст:
{context_block}

Отчет:
{report_text}

Верни только JSON без пояснений:
{{
  "report_result": "operations_created" | "text_only" | "no_actionable_data",
  "operations": [
    {{
      "product_name": "string",
      "operation_type_name": "string",
      "quantity": integer
    }}
  ]
}}
""".strip()

    @staticmethod
    def get_prompt_for_analytics_step(
        question: str,
        schema: str,
        request_context: str,
        previous_steps: str,
        max_limit: int,
    ) -> str:
        return f"""
Ты бизнес-аналитик. Выбери следующий шаг: final, sql или internet.

Смысл данных:
- Бизнес - реальная операционная деятельность, не Telegram-бот.
- Бот/backend - источник данных и интерфейс: отчеты=операции, смены=активность, комментарии=проблемы/идеи/риски, ставки/справочники=экономика операций.
- Используй эти данные для выводов о процессах бизнеса, но не называй преимуществом сам факт бота/отчетов/смен/комментариев/ручных справочников.
- Конкурентов/рынок сравнивай только по реальным продуктам, услугам, операциям, ценам, срокам, качеству, географии и клиентам. Если домен бизнеса не ясен, скажи, какие данные нужны.

Правила:
- sql: один read-only SELECT или WITH ... SELECT для SQLite; запрещены INSERT/UPDATE/DELETE/DROP/ALTER/CREATE/PRAGMA; LIMIT > {max_limit} нельзя.
- internet: только когда нужны внешние данные. Для конкурентов используй известный домен бизнеса из контекста/БД, не ищи конкурентов Telegram-бота.
- Не выдумывай факты. Если данных мало, укажи ограничения.
- Для sql/internet всегда добавляй comment.
- Верни только JSON без markdown.

Накопленный контекст админа:
{request_context}

Схема БД:
{schema}

Вопрос админа:
{question}

Уже полученные наблюдения:
{previous_steps}

Форматы ответа:
{{"action":"final","answer":"готовый ответ админу на русском"}}
{{"action":"sql","comment":"зачем нужен запрос","query":"SELECT ..."}}
{{"action":"internet","comment":"зачем нужен поиск","query":"короткий поисковый бриф"}}
""".strip()

    @staticmethod
    def get_prompt_for_internet_observation(
        question: str,
        research_query: str,
        max_chars: int,
    ) -> str:
        return f"""
Найди внешние данные для бизнес-аналитики. Это промежуточное наблюдение, не финальный ответ.

Ограничения:
- максимум {max_chars} символов;
- только факты/цифры/диапазоны/конкуренты/ссылки;
- без вступлений, повторов и длинных рассуждений;
- ищи рынок реального бизнеса, не Telegram-ботов/backend, если это прямо не указано;
- если бизнес-домен не указан, не подбирай случайных конкурентов: скажи, какие данные нужны;
- русский.

Исходный вопрос админа:
{question}

Что проверить во внешних источниках:
{research_query}
""".strip()

    @staticmethod
    def get_prompt_for_analytics_final_answer(
        question: str,
        request_context: str,
        previous_steps: str,
    ) -> str:
        return f"""
Ты бизнес-аналитик. Дай финальный ответ админу.

Правила смысла:
- Бизнес - реальная деятельность; бот/backend только источник данных.
- Данные бота используй как факты о процессах: операции, товары, объемы, ставки, проблемы, идеи, динамика.
- Не называй преимуществом сам факт бота/отчетов/смен/комментариев/ручных справочников.
- В сравнении с конкурентами говори о продуктах, услугах, операциях, ценах, качестве, сроках, географии, клиентах. Не сравнивай с ERP/ПО, если бизнес не ПО.

Накопленный контекст админа:
{request_context}

Вопрос админа:
{question}

Собранные наблюдения:
{previous_steps}

Требования к ответу:
- говори о бизнесе и его улучшении;
- разделяй факты из БД, внешние данные и свои выводы;
- не придумывай отсутствующие данные;
- если для сравнения с конкурентами не хватает описания реального бизнеса, продуктов/услуг, географии или типа конкурентов, скажи это и предложи, что добавить в /context;
- если есть неопределенность или конфликт данных, укажи это;
- русский язык;
- только JSON без markdown.

Формат:
{{"answer":"финальный ответ админу"}}
""".strip()
