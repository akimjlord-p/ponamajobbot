class Prompts:
    @staticmethod
    def get_prompt_for_synonym(word: str) -> str:
        return f"""
Тебе дано одно слово: название товара или операции.
Верни только полезные для распознавания варианты написания.

Правила:
- включи русский вариант;
- включи английский вариант, только если он реально используется;
- включи реалистичный транслит, если он помогает распознаванию;
- не добавляй абстрактные близкие по смыслу слова;
- не добавляй редкие или спорные варианты;
- все слова в нижнем регистре;
- только список через запятую без пробелов;
- без пояснений и дублей.

Слово: {word}
""".strip()

    @staticmethod
    def get_report_parsing_prompt(report_text: str, parsing_context: str | None = None) -> str:
        context_block = parsing_context or "Нет дополнительного контекста"

        return f"""
Ты парсер рабочих отчетов сотрудников.

Задача:
1. Определи, можно ли извлечь из отчета выполненные операции.
2. Если можно, верни список операций.
3. Операция:
   - operation_type_name: тип операции, например сборка/покраска/упаковка;
   - product_name: объект операции, например коробка/куртка/кружка;
   - quantity: количество выполненных действий, целое число.
   Пример: "покрасил 5 кружек" -> operation_type_name="покраска", product_name="кружка", quantity=5.
4. Если операций нет, но текст полезен для бизнеса, верни text_only.
5. Если отчет трудно разобрать или есть вопросы, верни no_actionable_data.
6. Если не уверен в операции или товаре, лучше верни no_actionable_data.

Дополнительный контекст:
{context_block}

Отчет:
{report_text}

Верни только JSON без пояснений:
{{
  "report_result": "operations_created" | "text_only" | "no_actionable_data",
  "operations": [
    {{
      "product_name": "string",
      "operation_type_name": "string",
      "quantity": integer
    }}
  ]
}}
""".strip()

    @staticmethod
    def get_prompt_for_analytics_step(
        question: str,
        schema: str,
        request_context: str,
        previous_steps: str,
        max_limit: int,
    ) -> str:
        return f"""
Ты бизнес-аналитик. Отвечай на вопросы админа о реальном бизнесе, а не о Telegram-боте.

Постоянные правила:
- Бизнес - это операционная деятельность компании.
- Telegram-бот и backend - только интерфейс сбора данных, аналитики и улучшения бизнеса.
- Рабочие через бот открывают/закрывают смены, отправляют отчеты и комментарии.
- Админ управляет справочниками, ставками, сотрудниками, накопительным бизнес-контекстом и задает аналитические вопросы.
- Контекст админа задается через команду /контекст, хранится в БД, складывается из записей и может быть пустым.
- Не подменяй бизнес обсуждением бота, если вопрос не про сам сервис.

Выбери один следующий шаг:
- final: данных достаточно, можно ответить сразу;
- sql: нужны внутренние данные из БД;
- internet: нужны внешние данные: конкуренты, рынок, тарифы, тренды, бенчмарки, отраслевые факты.

Правила действий:
- SQL: один read-only SELECT или WITH ... SELECT для SQLite.
- SQL-запрещено: INSERT, UPDATE, DELETE, DROP, ALTER, CREATE, PRAGMA и любые изменения данных.
- LIMIT больше {max_limit} недопустим.
- Internet используй только когда без внешних данных нельзя дать честный ответ. Запрос делай коротким и точным: что найти, где/для чего, без длинного контекста.
- Не выдумывай факты. Если данных мало, прямо укажи ограничения в final.
- Всегда добавляй comment к sql/internet: зачем нужен шаг.
- Верни только JSON без markdown.

Накопленный контекст админа:
{request_context}

Схема БД:
{schema}

Вопрос админа:
{question}

Уже полученные наблюдения:
{previous_steps}

Форматы ответа:
{{"action":"final","answer":"готовый ответ админу на русском"}}
{{"action":"sql","comment":"зачем нужен запрос","query":"SELECT ..."}}
{{"action":"internet","comment":"зачем нужен поиск","query":"короткий поисковый бриф"}}
""".strip()

    @staticmethod
    def get_prompt_for_internet_observation(
        question: str,
        research_query: str,
        max_chars: int,
    ) -> str:
        return f"""
Найди внешние данные для бизнес-аналитики. Это промежуточное наблюдение, не финальный ответ.

Ограничения, чтобы экономить токены:
- максимум {max_chars} символов;
- только факты, цифры, диапазоны, названия компаний/конкурентов и ссылки, если есть;
- без длинных рассуждений, вступлений и повторов;
- если надежных данных мало, так и скажи;
- русский язык.

Исходный вопрос админа:
{question}

Что проверить во внешних источниках:
{research_query}
""".strip()

    @staticmethod
    def get_prompt_for_analytics_final_answer(
        question: str,
        request_context: str,
        previous_steps: str,
    ) -> str:
        return f"""
Ты бизнес-аналитик. Дай финальный ответ админу по собранным наблюдениям.

Базовый контекст:
- Бизнес - реальная операционная деятельность компании.
- Telegram-бот/backend - инструмент сбора данных и аналитики, не сам бизнес.
- Рабочие заносят через бот смены, отчеты и комментарии.
- Админ ведет справочники, ставки, сотрудников, накопительный контекст и задает вопросы.
- Контекст админа может быть пустым; если его мало, опирайся только на факты из БД/внешних источников и явно отмечай ограничения.

Накопленный контекст админа:
{request_context}

Вопрос админа:
{question}

Собранные наблюдения:
{previous_steps}

Требования к ответу:
- говори о бизнесе и его улучшении;
- разделяй факты из БД, внешние данные и свои выводы;
- не придумывай отсутствующие данные;
- если есть неопределенность или конфликт данных, укажи это;
- русский язык;
- только JSON без markdown.

Формат:
{{"answer":"финальный ответ админу"}}
""".strip()
