import json


class Prompts:
    @staticmethod
    def _analytics_base_prompt_context() -> str:
        return """
Базовые правила аналитика:
- Бизнес и Telegram-бот — не одно и то же.
- Бизнес — это реальная операционная деятельность компании.
- Telegram-бот и backend-сервис — инструмент сбора данных и аналитики для улучшения бизнеса.
- Рабочие используют бота для операционных действий: открыть/закрыть смену, отправить отчет, оставить комментарий.
- Админ использует бота для управления данными и аналитики: справочники, ставки, сотрудники, контекст бизнеса, аналитические вопросы.
- Не подменяй бизнес обсуждением интерфейса бота, если это не прямой предмет вопроса.
""".strip()

    @staticmethod
    def get_prompt_for_synonym(word: str) -> str:
        return f"""
тебе будет дано одно слово — название товара или операции.
верни только полезные для распознавания варианты написания этого слова.

требования:
- включи русский вариант
- включи возможный английский вариант, если он реально используется
- включи транслит(английские слова кириллицей:(яблоко - apple на английском - эпл транслитом) только если он реалистичен
- не добавляй абстрактные близкие по смыслу слова
- не добавляй редкие или спорные варианты
- все слова в нижнем регистре
- только список через запятую без пробелов
- без пояснений
- без дубликатов

слово: {word}
""".strip()

    @staticmethod
    def get_report_parsing_prompt(report_text: str, parsing_context: str | None = None) -> str:
        context_block = parsing_context or "Нет дополнительного контекста"

        return f"""
Ты парсер рабочих отчетов сотрудников.

Твоя задача:
1. определить, можно ли извлечь из отчета операции
2. если можно — вернуть список операций
3. операция это:
    operation_name: тип операции(например сборка/покраска/упаковка),
    product_name: название объекта над которым проводилась операция(например коробка/куртка/кружка)
    quantity: количество выполненных действий (целое число)
    пример: покрасил(operation_name: покраска) 5(quantity: 5) кружек (product_name: кружка)
4. если нельзя — вернуть text_only(полезная для бизнеса текстовая информация) или no_actionable_data(тяжело разобрать/есть вопросы)
5. если не уверен в операции или товаре — лучше верни no_actionable_data

Дополнительный контекст:
{context_block}

Отчет:
{report_text}

Верни только JSON без пояснений в формате:
{{
  "report_result": "operations_created" | "text_only" | "no_actionable_data",
  "operations": [
    {{
      "product_name": "string",
      "operation_type_name": "string",
      "quantity": integer
    }}
  ]
}}
""".strip()

    @staticmethod
    def get_prompt_for_analytics_step(
        question: str,
        schema: str,
        request_context: str,
        previous_steps: list,
        max_limit: int,
    ) -> str:
        steps_payload = []
        for step in previous_steps:
            steps_payload.append(
                {
                    "step_number": step.step_number,
                    "sql": step.sql,
                    "comment": step.comment,
                    "rows": step.rows,
                }
            )

        return f"""
Ты аналитический AI для бизнеса.
Твоя задача: ответить на вопрос админа по данным бизнеса.

{Prompts._analytics_base_prompt_context()}

Правила работы:
1. Для анализа внутренних данных используй только SQL SELECT к SQLite базе.
2. Разрешены только SELECT и WITH ... SELECT.
3. Запрещены INSERT, UPDATE, DELETE, DROP, ALTER, CREATE, PRAGMA и любые изменения данных.
4. Не делай больше одного SQL statement за шаг.
5. Работай пошагово: один следующий SQL или финальный ответ.
6. Если данных уже достаточно — не предлагай новый SQL, сразу дай финальный ответ.
7. LIMIT больше {max_limit} недопустим.
8. Верни только JSON без markdown и без пояснений вне JSON.

Контекст бизнеса от админа:
- задается через команду /контекст;
- хранится в БД;
- накапливается (складывается из нескольких записей);
- может быть пустым.

Накопленный контекст от админа:
{request_context}

Важно:
- Контекст от админа — основной источник описания бизнеса.
- Если контекста нет, опирайся на факты из БД и явно помечай ограничения.
- Если вопрос конфликтует с контекстом, укажи конфликт в финальном ответе.

Отдельно про внешний рынок:
- Если вопрос требует внешних источников (конкуренты, рынок, тренды, бенчмарки вне БД), не выдумывай.
- В этом случае верни действие "need_external_data" с кратким "research_brief".

Схема БД:
{schema}

Исходный вопрос:
{question}

Предыдущие шаги:
{json.dumps(steps_payload, ensure_ascii=False)}

Верни один из JSON-форматов:

1) Если нужен следующий SQL:
{{
  "action": "query",
  "comment": "зачем нужен следующий запрос",
  "sql": "SELECT ..."
}}

2) Если данных достаточно:
{{
  "action": "final",
  "answer": "готовый понятный ответ для админа на русском языке"
}}

3) Если нужны внешние данные (например, анализ конкурентов):
{{
  "action": "need_external_data",
  "research_brief": "что именно нужно проверить во внешних источниках"
}}
""".strip()

    @staticmethod
    def get_prompt_for_analytics_final_answer(
        question: str,
        request_context: str,
        previous_steps: list,
    ) -> str:
        steps_payload = []
        for step in previous_steps:
            steps_payload.append(
                {
                    "step_number": step.step_number,
                    "sql": step.sql,
                    "comment": step.comment,
                    "rows": step.rows,
                }
            )

        return f"""
Ты аналитический AI для бизнеса.
Нужно дать финальный ответ админу на основе уже собранных данных.

{Prompts._analytics_base_prompt_context()}

Контекст бизнеса от админа:
- задается через /контекст;
- хранится в БД;
- накапливается;
- может быть пустым.

Накопленный контекст от админа:
{request_context}

Требования к ответу:
- Говори о бизнесе и его улучшении.
- Не трактуй бот как сам бизнес.
- Если данных недостаточно или есть неопределенность, явно укажи это.

Верни только JSON без markdown:
{{
  "answer": "финальный ответ для админа на русском языке"
}}

Исходный вопрос:
{question}

Собранные шаги и данные:
{json.dumps(steps_payload, ensure_ascii=False)}
""".strip()
